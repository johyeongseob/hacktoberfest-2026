"""Turn the Week 2 outputs into tables and figures.

Reads, under OUTPUTS (default outputs/, copied from the pod in setup.md step 9):
    eval/<run>-test/results.jsonl   one line per test episode (N = 0 is n0-test)
    eval/<run>-val.json             validation curve and the chosen step
    train/<run>.log                 training log (loss every 10 steps)

Writes, under RESULTS (default results/):
    tables.md                       all tables, with 95% Wilson intervals
    success_vs_n.png                success rate against demos per item
    wording_by_n.png                successes per wording and N
    overview.png                    the two above side by side
    training.png                    loss and validation curves

Runs on the laptop CPU in a few seconds (needs matplotlib):
    python tools/analyze.py
"""

import argparse
import json
import math
import re
from datetime import datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parents[1]  # the week-2 folder
NS = [0, 1, 3, 5, 10, 20, 40]
TAUGHT = ["A", "B", "C", "D"]
UNSEEN = ["E", "F", "G", "H"]
WORDINGS = ["original", *TAUGHT, *UNSEEN]
TRAINED_ITEMS = ["alphabet soup", "cream cheese", "butter", "orange juice"]
PRICE_PER_HOUR = 1.82  # A100 SXM with disks on RunPod, 2026-10-18
LOG_FREQ = 10  # run_train.sh logs the loss every 10 steps
CONTROL_HZ = 20  # LIBERO robot actions per second
SETS = {
    "taught": "Taught A-D",
    "unseen": "Unseen E-H",
    "original": "Original",
    "other": "Other 6 items",
}
COLORS = {"taught": "#1f77b4", "unseen": "#ff7f0e", "original": "#2ca02c", "other": "#7f7f7f"}
# Filled markers (●) for what the fine-tune saw, hollow (○) for what it did not, in both charts.
IN_TRAINING = {"taught", "original"}


def run_name(n: int) -> str:
    return "n0" if n == 0 else f"n{n}-s1000"


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% Wilson score interval for k successes out of n."""
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return max(0.0, centre - half), min(1.0, centre + half)


def set_of(row: dict) -> str:
    if row["item"] not in TRAINED_ITEMS:
        return "other"
    if row["wording"] == "original":
        return "original"
    return "taught" if row["wording"] in TAUGHT else "unseen"


def count(rows: list[dict], keep) -> tuple[int, int]:
    picked = [r for r in rows if keep(r)]
    return sum(r["success"] for r in picked), len(picked)


def cell(k: int, n: int, ci: bool = False) -> str:
    text = f"{k}/{n} ({100 * k / n:.0f}%)"
    if ci:
        lo, hi = wilson(k, n)
        text += f" [{100 * lo:.0f}-{100 * hi:.0f}]"
    return text


def md_table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def parse_log(path: Path) -> dict:
    text = path.read_text(errors="replace").replace("\r", "\n")
    # The log rounds steps from 1000 on ("step:1K"), so count the lines instead:
    # one every LOG_FREQ steps.
    losses = [float(v) for v in re.findall(r"step:\S+ .*?loss:([\d.]+)", text)]
    steps = [LOG_FREQ * (i + 1) for i in range(len(losses))]
    stamps = [datetime.strptime(s, "%Y-%m-%d %H:%M:%S") for s in re.findall(r"^INFO (\S+ \S+)", text, re.M)]
    return {"steps": steps, "losses": losses, "minutes": (stamps[-1] - stamps[0]).total_seconds() / 60}


def smooth(values: list[float], window: int = 10) -> list[float]:
    out = []
    for i in range(len(values)):
        chunk = values[max(0, i - window + 1) : i + 1]
        out.append(sum(chunk) / len(chunk))
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--outputs", type=Path, default=HERE / "outputs")
    parser.add_argument("--results", type=Path, default=HERE / "results")
    args = parser.parse_args()
    args.results.mkdir(parents=True, exist_ok=True)
    eval_root, train_root = args.outputs / "eval", args.outputs / "train"

    test = {}
    for n in NS:
        lines = (eval_root / f"{run_name(n)}-test" / "results.jsonl").read_text().splitlines()
        test[n] = [json.loads(line) for line in lines]
        assert len(test[n]) == 420, (n, len(test[n]))
    val = {n: json.loads((eval_root / f"{run_name(n)}-val.json").read_text()) for n in NS[1:]}
    logs = {n: parse_log(train_root / f"{run_name(n)}.log") for n in NS[1:]}

    out = ["# Week 2 results: tables", "",
           "Generated by `tools/analyze.py` from `outputs/`. Test set: initial states 0 to 9 "
           "(10 episodes per item and wording). Brackets are 95% Wilson intervals.", ""]

    # 1. Success by set and N.
    by_set = {n: {s: count(test[n], lambda r, s=s: set_of(r) == s) for s in SETS} for n in NS}
    out += ["## 1. Success by set", "",
            md_table(["Demos per item (N)", *SETS.values()],
                     [[str(n), *(cell(*by_set[n][s], ci=True) for s in SETS)] for n in NS]), ""]

    # 2. Success by wording and N (4 trained items x 10 episodes = 40 each).
    out += ["## 2. Success by wording (4 trained items, out of 40)", "",
            md_table(["Wording", *(f"N={n}" for n in NS)],
                     [[w, *(str(count(test[n], lambda r, w=w: r["item"] in TRAINED_ITEMS and r["wording"] == w)[0])
                            for n in NS)] for w in WORDINGS]), ""]

    # 3. Success by trained item: taught and unseen wordings (out of 40 each).
    rows = []
    for item in TRAINED_ITEMS:
        for s in ("taught", "unseen"):
            # Name the item on its first row only, so the two rows read as one group.
            rows.append([item if s == "taught" else "", SETS[s], *(str(count(test[n], lambda r, item=item, s=s: r["item"] == item and set_of(r) == s)[0])
                                          for n in NS)])
    out += ["## 3. Success by trained item (out of 40)", "",
            md_table(["Item", "Set", *(f"N={n}" for n in NS)], rows), ""]

    # 4. Other items, original wording (out of 10 each).
    others = sorted({r["item"] for r in test[0] if r["item"] not in TRAINED_ITEMS}, key=lambda i: next(
        r["task_id"] for r in test[0] if r["item"] == i))
    out += ["## 4. Other items, original wording (out of 10)", "",
            md_table(["Item", *(f"N={n}" for n in NS)],
                     [[item, *(str(count(test[n], lambda r, item=item: r["item"] == item)[0]) for n in NS)]
                      for item in others]), ""]

    # 5. Validation curve (A-D, initial states 10-14, 80 episodes).
    out += ["## 5. Validation (taught A-D, initial states 10 to 14, out of 80)", "",
            md_table(["N", "Step 1000", "Step 2000", "Step 3000", "Chosen step"],
                     [[str(n), *(str(p["successes"]) for p in val[n]["curve"]), str(val[n]["chosen_step"])]
                      for n in NS[1:]]), ""]

    # 6. Time the robot took in successful episodes (shorter = quicker), trained items.
    # Episode steps are robot actions at CONTROL_HZ, not training steps, so report seconds.
    rows = []
    for n in NS:
        cols = []
        for s in ("taught", "unseen", "original"):
            done = [r["steps"] / CONTROL_HZ for r in test[n] if set_of(r) == s and r["success"]]
            cols.append(f"{sum(done) / len(done):.1f} s" if done else "-")
        rows.append([str(n), *cols])
    out += ["## 6. Time to finish, successful episodes only", "",
            f"Seconds of robot motion ({CONTROL_HZ} actions per second, limit {280 // CONTROL_HZ} s). "
            "Failed episodes run to the limit and are left out.", "",
            md_table(["N", "Taught A-D", "Unseen E-H", "Original"], rows), ""]

    # 7. Cost and inference time.
    rows = []
    for n in NS:
        calls = sum(r["inference_calls"] for r in test[n])
        mean_call = sum(r["inference_total_s"] for r in test[n]) / calls
        if n == 0:
            rows.append(["0", "0", "-", "-", "-", f"{mean_call:.3f}"])
            continue
        minutes = logs[n]["minutes"]
        rows.append([str(n), str(4 * n), str(val[n]["chosen_step"]), f"{minutes:.0f}",
                     f"${minutes / 60 * PRICE_PER_HOUR:.2f}", f"{mean_call:.3f}"])
    out += ["## 7. Training time, cost, and inference time", "",
            "Training time is wall time from start to end of `lerobot-train`, while evaluation shared "
            f"the GPU; cost at ${PRICE_PER_HOUR}/hour. Inference time is the mean per SmolVLA call over "
            "the test set.", "",
            md_table(["N", "Demos (4 items)", "Chosen step", "Training minutes", "Training cost", "Seconds per call"],
                     rows), ""]
    (args.results / "tables.md").write_text("\n".join(out), encoding="utf-8")

    # Figures 1 and 2 are drawn by two helpers, once each on their own and once side by
    # side (overview.png), so the pair also works where images cannot be placed in a row.
    xs = list(range(len(NS)))
    n_ticks = ["0\n(no fine-tune)", *(str(n) for n in NS[1:])]
    grid = [[count(test[n], lambda r, w=w: r["item"] in TRAINED_ITEMS and r["wording"] == w)[0] for n in NS]
            for w in WORDINGS]

    def draw_success(ax) -> None:
        # Success rate against N, one line per set, with 95% Wilson bands.
        for s, label in SETS.items():
            ks = [by_set[n][s] for n in NS]
            ys = [100 * k / t for k, t in ks]
            lo = [100 * wilson(k, t)[0] for k, t in ks]
            hi = [100 * wilson(k, t)[1] for k, t in ks]
            ax.plot(xs, ys, marker="o", markersize=7, markeredgewidth=1.5, color=COLORS[s], label=label,
                    markerfacecolor=COLORS[s] if s in IN_TRAINING else "white")
            ax.fill_between(xs, lo, hi, color=COLORS[s], alpha=0.12)
        ax.set_xticks(xs, n_ticks)
        ax.set_xlabel("Training demos per item (N); each point is a separate fine-tuned model")
        ax.set_ylabel("Test success rate (%)")
        ax.set_ylim(0, 100)
        ax.grid(alpha=0.3)
        ax.legend(loc="lower right")
        ax.set_title("Test success by number of training demos (bands: 95% intervals)")

    def draw_wordings(fig, ax) -> None:
        # Wording x N heatmap of successes out of 40.
        im = ax.imshow(grid, cmap="Blues", vmin=0, vmax=40, aspect="auto")
        for i, row in enumerate(grid):
            for j, v in enumerate(row):
                ax.text(j, i, str(v), ha="center", va="center", color="white" if v > 26 else "black", fontsize=9)
        ax.set_xticks(xs, n_ticks)
        ax.set_yticks(range(len(WORDINGS)), ["original ●", *(f"{w} ●" for w in TAUGHT), *(f"{w} ○" for w in UNSEEN)])
        ax.axhline(4.5, color="black", linewidth=0.8)
        ax.set_xlabel("Training demos per item (N); each column is a separate model")
        ax.set_title("Successes out of 40 per wording (4 trained items x 10 episodes)")
        fig.colorbar(im, ax=ax, fraction=0.04)

    legend = "● in the fine-tuning data   ○ not in the fine-tuning data"
    fig, ax = plt.subplots(figsize=(7, 4.4))
    draw_success(ax)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.text(0.99, 0.01, legend, ha="right", fontsize=9)
    fig.savefig(args.results / "success_vs_n.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 4.6))
    draw_wordings(fig, ax)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.text(0.99, 0.01, legend, ha="right", fontsize=9)
    fig.savefig(args.results / "wording_by_n.png", dpi=150)
    plt.close(fig)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 4.8), gridspec_kw={"width_ratios": [1, 1.05]})
    draw_success(ax1)
    draw_wordings(fig, ax2)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.text(0.99, 0.01, legend, ha="right", fontsize=9)
    fig.savefig(args.results / "overview.png", dpi=150)
    plt.close(fig)

    # Figure 3: loss and validation curves.
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    cmap = plt.get_cmap("viridis")
    for i, n in enumerate(NS[1:]):
        color = cmap(i / (len(NS) - 2))
        assert logs[n]["steps"][-1] == 3000, (n, len(logs[n]["steps"]))
        ax1.plot(logs[n]["steps"], smooth(logs[n]["losses"]), color=color, label=f"N={n}")
        curve = val[n]["curve"]
        ax2.plot([p["step"] for p in curve], [100 * p["successes"] / p["episodes"] for p in curve],
                 marker="o", color=color, label=f"N={n}")
    ax1.set_xlabel("Training step")
    ax1.set_ylabel("Training loss (mean of last 10 logs)")
    ax1.set_title("Training loss")
    ax1.grid(alpha=0.3)
    ax1.legend()
    ax2.set_xlabel("Training step")
    ax2.set_ylabel("Validation success (%)")
    ax2.set_xticks([1000, 2000, 3000])
    ax2.set_ylim(50, 102)
    ax2.set_yticks(range(50, 101, 10))
    ax2.set_title("Validation: taught A-D, initial states 10-14")
    ax2.grid(alpha=0.3)
    ax2.legend()
    fig.tight_layout()
    fig.savefig(args.results / "training.png", dpi=150)
    plt.close(fig)

    print(f"Wrote {args.results}/tables.md, success_vs_n.png, wording_by_n.png, overview.png, training.png")


if __name__ == "__main__":
    main()
